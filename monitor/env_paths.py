# Comprehensive list of paths to check for exposed config files
# Based on env-checker's wordlist + common misconfigurations
#
# ──────────────────────────────────────────────────────────────────────────
# ORDER MATTERS. The deep scanner checks paths in this order. Tier-1 abort
# fires after the first ~150 paths give 0 hits, so the most-likely-to-leak
# paths MUST be in the front of the list. We prepend a `_TOP_TIER` block of
# the highest-yield paths (validated against env_found.jsonl history) and
# the dedup pass below keeps the first occurrence of each path, so anything
# duplicated later in the file becomes a no-op.
# ──────────────────────────────────────────────────────────────────────────

# Paths with the highest empirical hit rate or universal prevalence.
# This list is intentionally short (~50) so tier-1 fits in 150 slots even
# when combined with .env top entries below.
