# Deduplicate preserving order (case-insensitive key)
_seen: set[str] = set()
_deduped: list[str] = []
for _p in ENV_PATHS:
    _k = _p.lower().lstrip("/")
    if _k not in _seen:
        _seen.add(_k)
        _deduped.append(_p)
ENV_PATHS = _deduped

# Patterns that indicate valid env file content
import re

ENV_CONTENT_PATTERNS = [
    re.compile(r'^[A-Z_][A-Z0-9_]{2,}=.+', re.MULTILINE),           # KEY=value
    re.compile(r'^[A-Za-z_][A-Za-z0-9_]{2,}\s*=\s*.+', re.MULTILINE),  # key = value
    re.compile(r'export\s+[A-Z_][A-Z0-9_]{2,}=', re.MULTILINE),      # export KEY=value
    re.compile(r'aws_access_key_id', re.IGNORECASE),
    re.compile(r'\[default\].*aws_access_key_id', re.DOTALL | re.IGNORECASE),  # aws credentials
]

JUNK_INDICATORS = [
    re.compile(r'<html', re.IGNORECASE),
    re.compile(r'<!doctype', re.IGNORECASE),
    re.compile(r'<\?xml', re.IGNORECASE),
    re.compile(r'<script[\s>]', re.IGNORECASE),       # JS-only pages (login redirects)
    re.compile(r'<IfModule', re.IGNORECASE),           # .htaccess Apache config
    re.compile(r'Error 4\d\d', re.IGNORECASE),
    re.compile(r'NoSuchKey', re.IGNORECASE),
    re.compile(r'<Error>', re.IGNORECASE),
    re.compile(r'AccessDenied', re.IGNORECASE),
    re.compile(r'CDN Response:', re.IGNORECASE),       # CDN 404-in-200
    re.compile(r'404 Not Found', re.IGNORECASE),
    re.compile(r'Object Not Found', re.IGNORECASE),
    re.compile(r'location\.href\s*=', re.IGNORECASE),  # JS redirect
    re.compile(r'location\.replace\s*\(', re.IGNORECASE),
    re.compile(r'window\.location\s*=', re.IGNORECASE),
    re.compile(r'nginx', re.IGNORECASE),
    re.compile(r'apache', re.IGNORECASE),
]

_NULL_THRESHOLD = 0.05   # >5% null bytes → binary junk

# Real shell-style KEY=value at the start of a line.
# Used to reject JSON files where `=` only appears in base64 padding.
# Env-style assignment with a non-empty value. The trailing `\S` rejects
# `FOO=\n` (placeholder with no value) so a stray such line on a junk
# page can't masquerade as a real .env on its own.
_KV_LINE = re.compile(r'(?m)^\s*(?:export\s+)?[A-Za-z_][A-Za-z0-9_]{1,64}\s*=\s*\S')


def should_scan_content(content: str) -> bool:
    """Permissive gate — accepts JSON, YAML, TOML, INI, XML, PHP and any
    other text. Rejects only HTML pages, binary blobs and known error
    payloads. Key patterns (``sk-proj-…``, ``AKIA…``, ``ghp_…``) are
    self-identifying so they work in any text format.
    """
    if not content or len(content.strip()) < 5:
        return False
    if content.count('\x00') > len(content) * _NULL_THRESHOLD:
        return False
    head = content[:600]
    for pat in JUNK_INDICATORS:
        if pat.search(head):
            return False
    return True


def is_env_formatted(content: str) -> bool:
    """Is this body a real ``KEY=value`` style .env / .ini / shell file?

    Used to decide whether an *empty* .env (no extractable API keys) is
    still worth recording as evidence of an exposed file.
    """
    for pat in ENV_CONTENT_PATTERNS:
        if pat.search(content):
            return True
    # ≥1 real KEY=value line is enough — single-line .env files
    # (e.g. just ``DATABASE_URL=postgres://…``) are common in production.
    return len(_KV_LINE.findall(content)) >= 1


def is_valid_env_content(content: str) -> bool:
    """Strict env-shape check (kept for tests / external callers).

    The scanner itself uses ``should_scan_content`` + ``extract_keys`` +
    path heuristic to allow secrets to be pulled out of JSON/YAML configs
    too (firebase-config.json, application.yml, etc.).
    """
    return should_scan_content(content) and is_env_formatted(content)


def path_looks_like_env(path: str) -> bool:
    """Heuristic: is this URL path unambiguously an env/credentials file?

    Used to suppress false-positive 'found' rows for noisy paths like
    package.json, composer.lock, Jenkinsfile when no keys were extracted.
    """
    lp = path.lower().replace('%2e', '.').replace('%2f', '/')
    if '.env' in lp:
        return True
    if 'credentials' in lp or 'aws/credentials' in lp:
        return True
    if lp.endswith(('/.htpasswd', '/.netrc', '/secrets', '/secret',
                    '/config.env', '/env.list')):
        return True
    return False


